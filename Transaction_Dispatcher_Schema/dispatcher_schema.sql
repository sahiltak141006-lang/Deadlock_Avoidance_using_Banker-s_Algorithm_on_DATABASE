-- Oracle schema for the Priority Scheduler + Aging dispatcher.
-- Run once in the intended application schema (for example, in SQL*Plus).
-- This script intentionally stops on SQL errors rather than hiding them.
SET ECHO ON
SET SQLBLANKLINES ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

CREATE TABLE users (
    user_id       VARCHAR2(20) PRIMARY KEY,
    user_name     VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE accounts (
    account_id    VARCHAR2(30) PRIMARY KEY,
    user_id       VARCHAR2(20) NOT NULL,
    balance       NUMBER(14,2) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_accounts_user FOREIGN KEY (user_id) REFERENCES users(user_id),
    CONSTRAINT ck_account_balance CHECK (balance >= 0)
);

CREATE TABLE resource_types (
    resource_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_name VARCHAR2(100) NOT NULL UNIQUE,
    total_units   NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT ck_resource_units CHECK (total_units >= 0)
);

CREATE TABLE transactions (
    transaction_id        VARCHAR2(50) PRIMARY KEY,
    seq_no                NUMBER NOT NULL UNIQUE,
    user_id               VARCHAR2(20) NOT NULL,
    transaction_type      VARCHAR2(20) NOT NULL,
    source_account_id     VARCHAR2(30),
    destination_account_id VARCHAR2(30),
    amount                NUMBER(14,2) DEFAULT 0 NOT NULL,
    base_priority         NUMBER(1) NOT NULL,
    arrival_time          NUMBER DEFAULT 0 NOT NULL,
    duration              NUMBER DEFAULT 1 NOT NULL,
    transaction_status    VARCHAR2(20) DEFAULT 'QUEUED' NOT NULL,
    effective_priority    NUMBER(1) DEFAULT 0 NOT NULL,
    start_time            NUMBER,
    finish_time           NUMBER,
    waiting_time          NUMBER DEFAULT 0 NOT NULL,
    worker_id             NUMBER,
    blocked_count         NUMBER DEFAULT 0 NOT NULL,
    notes                 VARCHAR2(1000),
    created_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_txn_user FOREIGN KEY (user_id) REFERENCES users(user_id),
    CONSTRAINT fk_txn_source FOREIGN KEY (source_account_id) REFERENCES accounts(account_id),
    CONSTRAINT fk_txn_destination FOREIGN KEY (destination_account_id) REFERENCES accounts(account_id),
    CONSTRAINT ck_txn_type CHECK (transaction_type IN ('DEPOSIT','WITHDRAW','TRANSFER','BALANCE')),
    CONSTRAINT ck_txn_status CHECK (transaction_status IN ('QUEUED','BLOCKED','RUNNING','COMPLETED','FAILED','DEADLOCKED')),
    CONSTRAINT ck_txn_priority CHECK (base_priority BETWEEN 1 AND 5),
    CONSTRAINT ck_txn_effective_priority CHECK (effective_priority BETWEEN 0 AND 5),
    CONSTRAINT ck_txn_amount CHECK (amount >= 0),
    CONSTRAINT ck_txn_duration CHECK (duration >= 1),
    CONSTRAINT ck_txn_arrival CHECK (arrival_time >= 0),
    CONSTRAINT ck_txn_wait CHECK (waiting_time >= 0),
    CONSTRAINT ck_txn_blocked CHECK (blocked_count >= 0),
    CONSTRAINT ck_txn_type_amount CHECK (transaction_type = 'BALANCE' OR amount > 0),
    CONSTRAINT ck_txn_transfer_accounts CHECK (transaction_type <> 'TRANSFER' OR
        (source_account_id IS NOT NULL AND destination_account_id IS NOT NULL
         AND source_account_id <> destination_account_id)),
    CONSTRAINT ck_txn_account_shape CHECK (
        (transaction_type = 'DEPOSIT' AND destination_account_id IS NOT NULL) OR
        (transaction_type = 'WITHDRAW' AND source_account_id IS NOT NULL) OR
        (transaction_type = 'TRANSFER' AND source_account_id IS NOT NULL
            AND destination_account_id IS NOT NULL AND source_account_id <> destination_account_id) OR
        (transaction_type = 'BALANCE' AND source_account_id IS NOT NULL)
    )
);

CREATE TABLE transaction_resources (
    transaction_id VARCHAR2(50) NOT NULL,
    resource_id     NUMBER NOT NULL,
    max_claim       NUMBER NOT NULL,
    CONSTRAINT pk_transaction_resources PRIMARY KEY (transaction_id, resource_id),
    CONSTRAINT fk_tr_txn FOREIGN KEY (transaction_id) REFERENCES transactions(transaction_id),
    CONSTRAINT fk_tr_resource FOREIGN KEY (resource_id) REFERENCES resource_types(resource_id),
    CONSTRAINT ck_tr_claim CHECK (max_claim >= 0)
);

CREATE TABLE ledger (
    ledger_id      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR2(50) NOT NULL,
    account_id     VARCHAR2(30) NOT NULL,
    entry_type     VARCHAR2(30) NOT NULL,
    amount         NUMBER(14,2) NOT NULL,
    balance_after  NUMBER(14,2) NOT NULL,
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_ledger_txn FOREIGN KEY (transaction_id) REFERENCES transactions(transaction_id),
    CONSTRAINT fk_ledger_account FOREIGN KEY (account_id) REFERENCES accounts(account_id),
    CONSTRAINT ck_ledger_amount CHECK (amount >= 0),
    CONSTRAINT ck_ledger_balance CHECK (balance_after >= 0),
    CONSTRAINT uq_ledger_effect UNIQUE (transaction_id, account_id, entry_type)
);

CREATE TABLE event_log (
    event_id       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR2(50),
    event_type     VARCHAR2(40) NOT NULL,
    event_details  VARCHAR2(1000),
    event_time     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_event_txn FOREIGN KEY (transaction_id) REFERENCES transactions(transaction_id)
);

-- Database-level audit of every actual transaction status change.
-- This complements EVENT_LOG (which records scheduler lifecycle events).
CREATE TABLE transaction_status_audit (
    audit_id       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR2(50) NOT NULL,
    old_status     VARCHAR2(20),
    new_status     VARCHAR2(20) NOT NULL,
    changed_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_status_audit_txn FOREIGN KEY (transaction_id)
        REFERENCES transactions(transaction_id)
);

CREATE OR REPLACE TRIGGER trg_txn_status_audit
BEFORE UPDATE OF transaction_status ON transactions
FOR EACH ROW
WHEN (OLD.transaction_status <> NEW.transaction_status)
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
    INSERT INTO transaction_status_audit
        (transaction_id, old_status, new_status, changed_at)
    VALUES
        (:OLD.transaction_id, :OLD.transaction_status, :NEW.transaction_status, SYSTIMESTAMP);
END;
/

CREATE INDEX idx_status_audit_txn_time
    ON transaction_status_audit(transaction_id, changed_at);

CREATE TABLE benchmark_runs (
    run_id             NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    execution_mode     VARCHAR2(20) NOT NULL,
    total_transactions NUMBER DEFAULT 0 NOT NULL,
    committed_count    NUMBER DEFAULT 0 NOT NULL,
    rollback_count     NUMBER DEFAULT 0 NOT NULL,
    deadlock_count     NUMBER DEFAULT 0 NOT NULL,
    elapsed_ms         NUMBER,
    avg_wait_ms        NUMBER,
    throughput_tps     NUMBER,
    run_time           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_benchmark_mode CHECK (execution_mode IN ('VANILLA','DISPATCHER')),
    CONSTRAINT ck_benchmark_counts CHECK (total_transactions >= 0 AND committed_count >= 0
        AND rollback_count >= 0 AND deadlock_count >= 0)
);

CREATE INDEX idx_tx_status ON transactions(transaction_status);
CREATE INDEX idx_tx_arrival_seq ON transactions(arrival_time, seq_no);
CREATE INDEX idx_tx_source ON transactions(source_account_id);
CREATE INDEX idx_tx_destination ON transactions(destination_account_id);
CREATE INDEX idx_event_tx_time ON event_log(transaction_id, event_time);
CREATE INDEX idx_event_time ON event_log(event_time);
CREATE INDEX idx_ledger_account_time ON ledger(account_id, created_at);

CREATE OR REPLACE VIEW transaction_history_v AS
SELECT t.transaction_id, t.seq_no, u.user_name, t.transaction_type,
       t.source_account_id, t.destination_account_id, t.amount,
       t.base_priority, t.effective_priority, t.transaction_status,
       t.arrival_time, t.start_time, t.finish_time, t.waiting_time,
       t.worker_id, t.blocked_count, t.notes, t.created_at
FROM transactions t JOIN users u ON u.user_id = t.user_id;

CREATE OR REPLACE VIEW pending_transactions_v AS
SELECT transaction_id, seq_no, transaction_type, source_account_id,
       destination_account_id, amount, base_priority, effective_priority,
       arrival_time, duration, transaction_status
FROM transactions
WHERE transaction_status IN ('QUEUED','BLOCKED');

-- Seed a small demo account set. MERGE makes the seed section safe to rerun.
MERGE INTO users u USING (
    SELECT 'U001' user_id, 'Aarav' user_name FROM dual UNION ALL
    SELECT 'U002', 'Diya' FROM dual UNION ALL
    SELECT 'U003', 'Kabir' FROM dual UNION ALL
    SELECT 'U004', 'Meera' FROM dual UNION ALL
    SELECT 'U005', 'Rohan' FROM dual UNION ALL
    SELECT 'U006', 'Sana' FROM dual
) s ON (u.user_id = s.user_id)
WHEN MATCHED THEN UPDATE SET u.user_name = s.user_name
WHEN NOT MATCHED THEN INSERT (user_id, user_name) VALUES (s.user_id, s.user_name);

MERGE INTO accounts a USING (
    SELECT 'ACC101' account_id, 'U001' user_id, 12000 balance FROM dual UNION ALL
    SELECT 'ACC102', 'U002', 8500 FROM dual UNION ALL
    SELECT 'ACC103', 'U003', 17400 FROM dual UNION ALL
    SELECT 'ACC104', 'U004', 9200 FROM dual UNION ALL
    SELECT 'ACC105', 'U005', 15600 FROM dual UNION ALL
    SELECT 'ACC106', 'U006', 6300 FROM dual
) s ON (a.account_id = s.account_id)
WHEN MATCHED THEN UPDATE SET a.user_id = s.user_id
WHEN NOT MATCHED THEN INSERT (account_id, user_id, balance)
VALUES (s.account_id, s.user_id, s.balance);

MERGE INTO resource_types r USING (
    SELECT 'ACCOUNT_RESOURCE' resource_name, 6 total_units FROM dual UNION ALL
    SELECT 'LEDGER_RESOURCE', 2 FROM dual UNION ALL
    SELECT 'INVENTORY_RESOURCE', 5 FROM dual
) s ON (r.resource_name = s.resource_name)
WHEN MATCHED THEN UPDATE SET r.total_units = s.total_units
WHEN NOT MATCHED THEN INSERT (resource_name, total_units)
VALUES (s.resource_name, s.total_units);

COMMIT;

